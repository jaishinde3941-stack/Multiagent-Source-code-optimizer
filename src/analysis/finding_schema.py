"""
Normalized Finding Schema and Deduplication Logic for C/C++ Code Analysis.

Provides a unified, structured representation for findings generated by compilers,
static analyzers (Clang-Tidy, Cppcheck), runtime sanitizers (ASan, UBSan),
rule-based scanners, and LLM reasoning.
"""

from dataclasses import dataclass, field, asdict
from typing import Any, Dict, List, Optional, Tuple
import uuid


@dataclass
class Finding:
    """
    Normalized finding schema representing a code defect, vulnerability,
    or performance/quality observation.
    """
    id: str = field(default_factory=lambda: f"finding-{uuid.uuid4().hex[:8]}")
    type: str = "unknown"
    category: str = "correctness"       # "correctness" | "security" | "performance" | "quality"
    description: str = ""
    severity: str = "medium"            # "critical" | "high" | "medium" | "low" | "info"
    confidence: float = 0.8             # 0.0 to 1.0
    source_tool: str = "unknown"        # "clang" | "clang-tidy" | "cppcheck" | "asan" | "ubsan" | "rule" | "llm" | "heuristic"
    file_path: str = "<source>"
    line: Optional[int] = None
    column: Optional[int] = None
    evidence: str = ""
    recommendation: str = ""
    cwe_id: Optional[str] = None
    execution_context: Dict[str, Any] = field(default_factory=dict)
    status: str = "potential"           # "confirmed" | "potential" | "suspicious" | "code_quality" | "manual_review" | "unrun"
    is_confirmed: bool = False
    related_findings: List[str] = field(default_factory=list)
    raw_diagnostic: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        """Convert finding to standard dictionary representation."""
        data = asdict(self)
        data["source"] = self.source_tool
        return data

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "Finding":
        """Construct Finding from dictionary, preserving existing fields."""
        cleaned = dict(data)
        # Fallbacks for legacy/alternative field names
        if "source" in cleaned and "source_tool" not in cleaned:
            cleaned["source_tool"] = cleaned["source"]
        valid_keys = {
            "id", "type", "category", "description", "severity", "confidence",
            "source_tool", "file_path", "line", "column", "evidence",
            "recommendation", "cwe_id", "execution_context", "status",
            "is_confirmed", "related_findings", "raw_diagnostic"
        }
        filtered = {k: v for k, v in cleaned.items() if k in valid_keys}
        if "id" not in filtered or not filtered["id"]:
            filtered["id"] = f"finding-{uuid.uuid4().hex[:8]}"
        return cls(**filtered)


def normalize_finding(raw: Dict[str, Any], default_source: str = "unknown") -> Dict[str, Any]:
    """Ensure dictionary complies with the Finding schema."""
    if isinstance(raw, Finding):
        return raw.to_dict()
    f = Finding.from_dict(raw)
    if f.source_tool == "unknown" and default_source != "unknown":
        f.source_tool = default_source
    return f.to_dict()


def deduplicate_findings(findings: List[Dict[str, Any]]) -> Tuple[List[Dict[str, Any]], Dict[str, Any]]:
    """
    Deduplicate overlapping findings conservatively while preserving provenance.

    Strategy:
    - Group findings by (normalized_type, line).
    - If multiple tools flag the same issue on the same line, merge them into a single
      primary finding, record all source tools in provenance, and link related IDs.
    - Do NOT merge distinct vulnerability types or issues on different lines.
    - Higher severity and higher confidence take precedence.
    - If any tool confirmed the issue (e.g., dynamic sanitizer or exact rule match),
      mark as confirmed.

    Returns:
        (deduplicated_findings, deduplication_summary)
    """
    if not findings:
        return [], {"original_count": 0, "deduplicated_count": 0, "merged_groups": 0}

    # Severity ranking: critical > high > medium > low > info
    sev_rank = {"critical": 5, "high": 4, "medium": 3, "low": 2, "info": 1}

    def _type_family(ftype: str) -> str:
        """Map tool-specific check names to general defect families for conservative grouping."""
        t = ftype.lower().replace("-", "_")
        if "buffer" in t or "overflow" in t or "out_of_bounds" in t or "array_subscript" in t:
            return "buffer_overflow"
        if "uninit" in t:
            return "uninitialized_variable"
        if "null" in t and ("pointer" in t or "deref" in t):
            return "null_dereference"
        if "leak" in t or "free" in t and "leak" in t:
            return "memory_leak"
        if "div" in t and "zero" in t:
            return "division_by_zero"
        if "format" in t and "string" in t:
            return "format_string"
        return t

    groups: Dict[Tuple[str, Optional[int]], List[Dict[str, Any]]] = {}
    for raw_f in findings:
        f = normalize_finding(raw_f)
        key = (_type_family(f.get("type", "")), f.get("line"))
        groups.setdefault(key, []).append(f)

    merged_findings: List[Dict[str, Any]] = []
    merged_groups_count = 0

    for key, group in groups.items():
        if len(group) == 1:
            merged_findings.append(group[0])
            continue

        merged_groups_count += 1
        # Pick highest severity and confidence
        group.sort(
            key=lambda item: (
                sev_rank.get(item.get("severity", "medium").lower(), 2),
                item.get("confidence", 0.5),
            ),
            reverse=True,
        )
        primary = dict(group[0])
        all_ids = [item.get("id") for item in group if item.get("id")]
        all_sources = list(dict.fromkeys(item.get("source_tool", "unknown") for item in group))
        all_evidences = [item.get("evidence") for item in group if item.get("evidence")]
        all_cwes = list(dict.fromkeys(item.get("cwe_id") for item in group if item.get("cwe_id")))

        primary["related_findings"] = [i for i in all_ids if i != primary.get("id")]
        primary["execution_context"] = dict(primary.get("execution_context", {}))
        primary["execution_context"]["provenance_sources"] = all_sources
        primary["execution_context"]["subsumed_finding_ids"] = all_ids

        # If any tool confirmed it, it is confirmed
        if any(item.get("is_confirmed", False) or item.get("status") == "confirmed" for item in group):
            primary["is_confirmed"] = True
            primary["status"] = "confirmed"

        if all_cwes and not primary.get("cwe_id"):
            primary["cwe_id"] = all_cwes[0]

        if all_evidences and not primary.get("evidence"):
            primary["evidence"] = " | ".join(dict.fromkeys(all_evidences))

        merged_findings.append(primary)

    summary = {
        "original_count": len(findings),
        "deduplicated_count": len(merged_findings),
        "merged_groups": merged_groups_count,
    }
    return merged_findings, summary
